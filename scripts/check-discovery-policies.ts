import assert from "node:assert/strict";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { PolicyPreviewResponseSchema, PublicPolicySchema } from "../discovery/src/policy-model";
import { replayPolicyPreview } from "../discovery/src/policies";
const base = "http://127.0.0.1:8794/api/10x";
const token = readFileSync(new URL("../discovery/.dev.vars", import.meta.url), "utf8").match(/^TENX_ADMIN_TOKEN=([a-f0-9]{64})\s*$/m)?.[1];
if (!token) throw new Error("Start local discovery first");
const currentResponse = await fetch(`${base}/transparency/policies`);
assert.equal(currentResponse.status, 200);
const before = PublicPolicySchema.parse((await currentResponse.json() as { data: unknown }).data);
const request = { request_id: crypto.randomUUID(), reason: "Local PRD checkpoint: compare a stricter $50K liquidity floor without changing evidence gates", edits: { min_liquidity_usd: 50000 } };
const post = () => fetch(`${base}/admin/policies/preview`, { method: "POST", headers: { authorization: `Bearer ${token}`, "content-type": "application/json" }, body: JSON.stringify(request) });
const response = await post(), value: unknown = await response.json();
assert.equal(response.status, 200, JSON.stringify(value));
const result = PolicyPreviewResponseSchema.parse(value);
await replayPolicyPreview(result.record);
const retry = PolicyPreviewResponseSchema.parse(await (await post()).json());
assert.equal(retry.record.record_hash, result.record.record_hash);
const savedResponse = await fetch(`${base}/admin/policies/previews/${request.request_id}`, { headers: { authorization: `Bearer ${token}` } });
const saved = PolicyPreviewResponseSchema.parse(await savedResponse.json());
assert.equal(saved.record.record_hash, result.record.record_hash);
const after = PublicPolicySchema.parse((await (await fetch(`${base}/transparency/policies`)).json() as { data: unknown }).data);
assert.equal(before.policy_hash, after.policy_hash);
assert.equal((await fetch(`${base}/admin/policies/previews/${request.request_id}`)).status, 401);
mkdirSync(new URL("../.tmp/", import.meta.url), { recursive: true });
writeFileSync(new URL("../.tmp/policy-preview-local.json", import.meta.url), JSON.stringify(result, null, 2));
console.log(JSON.stringify({ id: result.record.id, candidates: result.record.inputs.baseline.candidates.length, baseline: result.record.result.baseline.counts, proposed: result.record.result.proposed.counts, changed: result.record.result.changed.length, replay: result.replay, retry_same_record: true, active_policy_unchanged: true, source_requests_made_by_this_check: 0 }, null, 2));
